/** Get service by slug */
export function getServiceBySlug(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug && s.is_active)
}

/** Get services by category */
export function getServicesByCategory(categoryId: string): Service[] {
  return activeServices.filter((s) => s.category_id === categoryId)
}

/** Get related services — same category, different id, max 3 */
export function getRelatedServices(serviceId: string, limit = 3): Service[] {
  const service = services.find((s) => s.id === serviceId)
  if (!service) return []
  return activeServices
    .filter((s) => s.category_id === service.category_id && s.id !== serviceId)
    .slice(0, limit)
}

